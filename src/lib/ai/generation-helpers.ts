import type { GoogleGenAI } from '@google/genai';
import { AI_MAX_OUTPUT_TOKENS, AI_TIMEOUT_MS } from '@/lib/constants';
import { PLAN_GENERATION_OUTPUT_SCHEMA } from './prompts';
import { getDemoIdeas } from './demo-engine';
import { IdeasSchema } from '@/domain/schemas/ideas';
import type { Ideas } from '@/domain/schemas/ideas';
import type { EventType } from '@/lib/constants';
import type { GenerationResult } from './client';

export function buildDemoFallbackResult(
  eventType: EventType,
  statusMessage: string,
): GenerationResult {
  const demoIdeas = getDemoIdeas(eventType);
  demoIdeas.provenance = {
    source: 'demo_engine',
    timestamp: new Date().toISOString(),
    label: 'Demo engine',
  };
  return {
    ideas: demoIdeas,
    isDemoFallback: true,
    statusMessage,
  };
}

export async function requestModelContent(
  client: GoogleGenAI,
  model: string,
  userPrompt: string,
  systemInstruction: string,
): Promise<string> {
  const generatePromise = client.models.generateContent({
    model,
    contents: userPrompt,
    config: {
      systemInstruction,
      maxOutputTokens: AI_MAX_OUTPUT_TOKENS,
      responseMimeType: 'application/json',
      responseSchema: PLAN_GENERATION_OUTPUT_SCHEMA,
      temperature: 0.7,
    },
  });

  const timeoutPromise = new Promise<never>((_, reject) =>
    setTimeout(() => reject(new Error('AI generation timed out')), AI_TIMEOUT_MS),
  );

  const response = await Promise.race([generatePromise, timeoutPromise]);
  const rawText = response.text?.trim();

  if (!rawText) {
    throw new Error('Empty response from model');
  }

  return rawText;
}

function isNonEmptyArray<T>(val: unknown): val is T[] {
  return Array.isArray(val) && val.length > 0;
}

function getNonEmptyArray<T>(val: unknown, fallback: T[]): T[] {
  if (isNonEmptyArray<T>(val)) {
    return val;
  }
  return fallback;
}

export function repairPartialIdeas(
  json: Record<string, unknown>,
  eventType: EventType,
  model: string,
): Ideas | null {
  const fallback = getDemoIdeas(eventType);
  const repaired: Ideas = {
    themes: getNonEmptyArray(json.themes, fallback.themes),
    colorPalettes: getNonEmptyArray(json.colorPalettes, fallback.colorPalettes),
    menuIdeas: getNonEmptyArray(json.menuIdeas, fallback.menuIdeas),
    activities: getNonEmptyArray(json.activities, fallback.activities),
    decor: getNonEmptyArray(json.decor, fallback.decor),
    dayTimeline: getNonEmptyArray(json.dayTimeline, fallback.dayTimeline),
    vendorQuestions: getNonEmptyArray(json.vendorQuestions, fallback.vendorQuestions),
    provenance: {
      source: 'gemini',
      modelId: model,
      timestamp: new Date().toISOString(),
      label: `Generated by Gemini - ${model} - ${new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}`,
    },
  };

  const result = IdeasSchema.safeParse(repaired);
  return result.success ? result.data : null;
}
