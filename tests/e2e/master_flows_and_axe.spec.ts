import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test.describe('3.2: Master E2E User Flows & Comprehensive Axe-Core Scans', () => {
  // Helper to run axe and assert zero serious or critical violations
  async function assertAxeZeroViolations(page: any, contextName: string) {
    const results = await new AxeBuilder({ page })
      .exclude('#next-logo')
      .exclude('[data-nextjs-dev-tools-button]')
      .withTags(['wcag2a', 'wcag2aa'])
      .analyze();

    const seriousOrCritical = results.violations.filter(
      (v) => v.impact === 'serious' || v.impact === 'critical',
    );

    if (seriousOrCritical.length > 0) {
      console.error(`Axe violations in ${contextName}:`, JSON.stringify(seriousOrCritical, null, 2));
    }
    expect(seriousOrCritical, `Expected 0 serious/critical axe violations in ${contextName}`).toEqual([]);
  }

  // 1. Happy path wizard completion for Wedding
  test('happy path: wedding plan creation from welcome to overview with provenance badge', async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.goto('/');
    await page.waitForLoadState('networkidle');

    // Click "New Plan"
    await page.getByRole('button', { name: /New Plan/i }).click();
    const dialog = page.getByRole('dialog');
    await expect(dialog).toBeVisible();

    // Welcome view axe scan
    await assertAxeZeroViolations(page, 'Onboarding Welcome View');

    // Start New Plan Wizard
    await dialog.getByRole('button', { name: /Start New Plan Wizard/i }).click();

    // Step 1: Wedding & Title
    await dialog.getByRole('button', { name: /^Wedding$/i }).click();
    const titleInput = dialog.locator('#field-event-name');
    await titleInput.fill('Eleanor & Thomas Autumn Wedding');
    await assertAxeZeroViolations(page, 'Wizard Step 1');
    await dialog.getByRole('button', { name: 'Next', exact: true }).click();

    // Step 2: Date & Location
    const dateInput = dialog.locator('#field-event-date');
    await dateInput.fill('2027-10-16');
    const cityInput = dialog.locator('#field-city');
    await cityInput.fill('Hudson Valley, NY');
    await assertAxeZeroViolations(page, 'Wizard Step 2');
    await dialog.getByRole('button', { name: 'Next', exact: true }).click();

    // Step 3: Budget
    await assertAxeZeroViolations(page, 'Wizard Step 3');
    await dialog.getByRole('button', { name: 'Next', exact: true }).click();

    // Step 4: Priorities & Inclusions
    await assertAxeZeroViolations(page, 'Wizard Step 4');
    await dialog.getByRole('button', { name: /Generate Plan/i }).click();

    // Assert plan generated and rendered on Overview with provenance badge
    await expect(dialog).not.toBeVisible({ timeout: 25000 });
    await expect(page.getByRole('heading', { name: 'Eleanor & Thomas Autumn Wedding' })).toBeVisible();
    await expect(page.locator('text=Generated by Gemini').or(page.locator('text=Demo engine')).first()).toBeVisible();
  });

  // 2. Happy path for Birthday with Scalloped Theme
  test('happy path: birthday plan creation with birthday theme', async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.goto('/');
    await page.waitForLoadState('networkidle');

    await page.getByRole('button', { name: /New Plan/i }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByRole('button', { name: /Start New Plan Wizard/i }).click();

    await dialog.getByRole('button', { name: /^Birthday$/i }).click();
    await dialog.locator('#field-event-name').fill('Lucas 40th Birthday');
    await dialog.getByRole('button', { name: 'Next', exact: true }).click();

    await dialog.locator('#field-event-date').fill('2027-08-20');
    await dialog.locator('#field-city').fill('Chicago, IL');
    await dialog.getByRole('button', { name: 'Next', exact: true }).click();
    await dialog.getByRole('button', { name: 'Next', exact: true }).click();

    await dialog.getByRole('button', { name: /Generate Plan/i }).click();
    await expect(dialog).not.toBeVisible({ timeout: 25000 });
    await expect(page.getByRole('heading', { name: 'Lucas 40th Birthday' })).toBeVisible();
  });

  // 3. Happy path for Community Gathering with Teal Theme
  test('happy path: community event creation with community theme', async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.goto('/');
    await page.waitForLoadState('networkidle');

    await page.getByRole('button', { name: /New Plan/i }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByRole('button', { name: /Start New Plan Wizard/i }).click();

    await dialog.getByRole('button', { name: /^Community$/i }).click();
    await dialog.locator('#field-event-name').fill('Midsummer Neighborhood Fair');
    await dialog.getByRole('button', { name: 'Next', exact: true }).click();

    await dialog.locator('#field-event-date').fill('2027-07-10');
    await dialog.locator('#field-city').fill('Portland, OR');
    await dialog.getByRole('button', { name: 'Next', exact: true }).click();
    await dialog.getByRole('button', { name: 'Next', exact: true }).click();

    await dialog.getByRole('button', { name: /Generate Plan/i }).click();
    await expect(dialog).not.toBeVisible({ timeout: 25000 });
    await expect(page.getByRole('heading', { name: 'Midsummer Neighborhood Fair' })).toBeVisible();
  });

  // 4. Mobile 360x640 path
  test('mobile 360x640 path: navigation and budget view', async ({ page }) => {
    await page.setViewportSize({ width: 360, height: 640 });
    await page.goto('/');
    await page.waitForLoadState('networkidle');

    // Overview axe scan mobile
    await assertAxeZeroViolations(page, 'Mobile Overview');

    // Navigate to Budget view via mobile bottom nav
    await page.getByRole('button', { name: 'Budget', exact: true }).click();
    await expect(page.getByRole('heading', { name: /Budget & Allocation/i })).toBeVisible();
    await assertAxeZeroViolations(page, 'Mobile Budget View');
  });

  // 5. Failure paths via route mocking (500 and 429)
  test('failure path: AI route 500 returns honest demo engine fallback', async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 900 });

    // Mock /api/generate to return 500
    await page.route('**/api/generate', (route) => {
      route.fulfill({
        status: 500,
        contentType: 'application/json',
        body: JSON.stringify({ error: 'Internal AI provider timeout' }),
      });
    });

    await page.goto('/');
    await page.waitForLoadState('networkidle');

    await page.getByRole('button', { name: /New Plan/i }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByRole('button', { name: /Start New Plan Wizard/i }).click();

    await dialog.locator('#field-event-name').fill('Resilient Fallback Celebration');
    await dialog.getByRole('button', { name: 'Next', exact: true }).click();
    await dialog.locator('#field-event-date').fill('2027-11-15');
    await dialog.locator('#field-city').fill('Denver, CO');
    await dialog.getByRole('button', { name: 'Next', exact: true }).click();
    await dialog.getByRole('button', { name: 'Next', exact: true }).click();

    await dialog.getByRole('button', { name: /Generate Plan/i }).click();

    // Should gracefully fall back to demo plan without crashing
    await expect(dialog).not.toBeVisible({ timeout: 10000 });
    await expect(page.getByRole('heading', { name: 'Resilient Fallback Celebration' })).toBeVisible();
    await expect(page.getByRole('region', { name: 'Event Summary' }).getByText('Demo engine')).toBeVisible();
  });

  // 6. Axe scans across EVERY view and modal in each theme and reduce-decoration mode
  test('axe scan: Budget, Timeline, Checklist, Ideas, Copilot, Compare, Modals in all themes', async ({ page }) => {
    test.setTimeout(120000);
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.goto('/');
    await page.waitForLoadState('networkidle');

    // Overview in Wedding theme
    await assertAxeZeroViolations(page, 'Overview View (Wedding)');

    // Budget View
    await page.getByRole('button', { name: 'Budget & Sliders' }).click();
    await assertAxeZeroViolations(page, 'Budget View');

    // Timeline View
    await page.getByRole('button', { name: 'Timeline & Gantt' }).click();
    await assertAxeZeroViolations(page, 'Timeline View');

    // Checklist View
    await page.getByRole('button', { name: 'Vendor Pipeline' }).click();
    await assertAxeZeroViolations(page, 'Checklist View');

    // Ideas View
    await page.getByRole('button', { name: 'Creative Ideas' }).click();
    await assertAxeZeroViolations(page, 'Ideas View');

    // Copilot View
    await page.getByRole('button', { name: 'Planning Copilot' }).click();
    await assertAxeZeroViolations(page, 'Copilot View');

    // Compare View
    await page.getByRole('button', { name: 'Scenario Compare' }).click();
    await assertAxeZeroViolations(page, 'Compare View');

    // Export Modal
    await page.getByRole('button', { name: /Export/i }).click();
    await assertAxeZeroViolations(page, 'Export Modal');
    await page.getByRole('button', { name: 'Close export dialog' }).click();
    await expect(page.getByRole('dialog')).not.toBeVisible();

    // Shortcuts Modal
    await page.keyboard.press('?');
    await assertAxeZeroViolations(page, 'Shortcuts Modal');
    await page.getByRole('button', { name: 'Close keyboard shortcuts dialog' }).click();
    await expect(page.getByRole('dialog')).not.toBeVisible();

    // Reduce decoration mode
    await page.getByRole('button', { name: /Decoration:/i }).click();
    await assertAxeZeroViolations(page, 'Reduce Decoration Mode');
  });
});
